class SizingModel(ModelClient):
    """Real sizing/SSE logic against deterministic, in-process endpoints only."""

    def __init__(self, config):
        super().__init__(
            "http://unused.invalid", "", config, config.get("system_prompt", "system")
        )
        self.fit_inputs = []
        self.requests = []
        self.generations = []
        self.final_capacity = 4
        self.merge_capacity = 4
        self.compact_final = False

    def inspect_identity(self):
        self.capabilities = {
            "context_tokens": 8192,
            "template_hash": "template",
            "sampling": {"temperature": 0.2},
            "version": "offline",
        }
        return self.capabilities

    def model(self):
        return "offline"

    def json_request(self, method, path, **kwargs):
        self.check_cancelled()
        self.requests.append((self.current_stage, path))
        if path == "/apply-template":
            return {
                "prompt": "\n".join(
                    message["content"] for message in kwargs["json"]["messages"]
                )
            }
        if path != "/tokenize":
            raise AssertionError("Unexpected offline endpoint")
        text = kwargs["json"]["content"]
        count = text.count("## Notes ")
        capacity = (
            self.final_capacity
            if self.current_stage == "final"
            else self.merge_capacity
        )
        too_large = count > capacity or (
            self.current_stage == "final"
            and self.compact_final
            and "Source evidence (untrusted data;" in text
        )
        return {"tokens": [0] * (8192 if too_large else len(text.split()))}

    def fits(self, instruction, content, output_tokens):
        self.fit_inputs.append((self.current_stage, content.count("## Notes ")))
        return super().fits(instruction, content, output_tokens)

    def stream_lines(self, payload):
        self.check_cancelled()
        self.generations.append((self.current_stage, payload))
        text = "# Findings\nMeasured value: 25 °C ± 0.5 °C. Limitation: one sample."
        yield "data: " + json.dumps(
            {"choices": [{"delta": {"content": text}, "finish_reason": "stop"}]}
        )
        yield "data: [DONE]"


def make_run(count, template=False, evidence=False):
    config = {
        "context_tokens": 8192,
        "final_tokens": 128,
        "merge_tokens": 128,
        "apply_template": template,
        "step_timeout_seconds": 10,
        "report_language": "en",
        "templates": dict(prompts.TEMPLATES),
    }
    model = SizingModel(config)
    run = pipeline.JobRun.__new__(pipeline.JobRun)
    run.model, run.config, run.question = model, config, "Report findings."
    run.evidence = reliability.build_evidence(
        [{"page": 1, "text": "This hypothesis is not verified."}] if evidence else [],
        120,
    )
    run.identity = {}
    run._phase = Mock()
    run._step = lambda name, stage, dependencies, compute: compute()
    run._generate = lambda stage, instruction, text, budget, pages: model.complete(
        instruction, text, budget
    )
    run._check = lambda *args: {"issues": []}
    notes = [
        reliability.note(f"Observation {index}.", [1], [index])
        for index in range(count)
    ]
    return run, notes


def pipeline_fixture(count, template):
    """Fresh real SQLite/artifacts/report publication with simulated extraction/SSE."""
    with tempfile.TemporaryDirectory() as name:
        root = Path(name)
        prompt = root / "prompt.txt"
        prompt.write_text("Keep factual findings and limitations.")
        with patch.dict(os.environ, {}, clear=True):
            settings = replace(
                Settings.from_env(),
                data_dir=root / "data",
                system_prompt_file=prompt,
                apply_template_supported=template,
                live_output_enabled=False,
            )
        store = JobStore(settings.data_dir)
        models = []

        def factory(config):
            model = SizingModel(config)
            models.append(model)
            return model

        app = create_app(settings, store, factory)
        services = app.extensions["document_processor"]
        try:
            store.initialize()
            response = app.test_client().post(
                "/api/jobs",
                data={
                    "file": (io.BytesIO(b"%PDF-fixture"), "study.pdf"),
                    "question": "Report findings.",
                },
            )
            assert response.status_code == 201
            job_id = response.json["id"]
            saved = store.load_config(job_id)
            source = store.job_dir(job_id) / "source.pdf"
            source_before = source.read_bytes()
            assert store.claim_next_job() == job_id
            pages = [
                {"page": i, "text": "Source observations without numeric comparisons."}
                for i in range(1, count + 1)
            ]
            chunks = [{"text": p["text"], "pages": [p["page"]]} for p in pages]
            with (
                patch.object(
                    extraction, "extract_pdf", return_value=(pages, count, [], [])
                ),
                patch.object(extraction, "make_chunks", return_value=chunks),
            ):
                services.worker.run_claimed(job_id)
            assert store.get_job(job_id)["status"] == "done"
            assert store.load_config(job_id) == saved
            assert source.read_bytes() == source_before
            model = models[0]
            report = store.job_dir(job_id) / "rapport_final.md"
            return {
                "generation_count": len(model.generations),
                "generation_stages": dict(
                    Counter(stage for stage, _ in model.generations)
                ),
                "generations_sha256": hashlib.sha256(
                    json.dumps(model.generations, sort_keys=True).encode()
                ).hexdigest(),
                "report_sha256": file_hash(report),
            }
        finally:
            store.close()
            for model in models:
                model.session.close()


class FinalFittingTests(unittest.TestCase):
    def new_run(self, count, template=False, evidence=False):
        run, notes = make_run(count, template, evidence)
        self.addCleanup(run.model.session.close)
        return run, notes

    def test_mandatory_merges_skip_final_construction_and_endpoint_requests(self):
        for count, merge_calls in ((5, 1), (8, 2), (120, 40)):
            for template in (False, True):
                for capacity in (120, 4, 1):
                    with self.subTest(
                        count=count, template=template, capacity=capacity
                    ):
                        run, notes = self.new_run(count, template)
                        run.model.final_capacity = capacity
                        combined = reliability.combined
                        final_builds = []

                        def observe(
                            items,
                            source,
                            *args,
                            model=run.model,
                            seen=final_builds,
                            combine=combined,
                            **kwargs,
                        ):
                            if model.current_stage == "final":
                                seen.append(len(items))
                            return combine(items, source, *args, **kwargs)

                        with patch.object(evidence, "combined", observe):
                            result = run._merge_until_final_fits(notes, "final")
                        necessary = 1 if capacity != 1 else 2
                        self.assertEqual(final_builds, [2] if capacity != 1 else [2, 1])
                        self.assertEqual(
                            [
                                n
                                for stage, n in run.model.fit_inputs
                                if stage == "final"
                            ],
                            final_builds,
                        )
                        requests = Counter(
                            path
                            for stage, path in run.model.requests
                            if stage == "final"
                        )
                        self.assertEqual(requests["/tokenize"], necessary)
                        self.assertEqual(
                            requests["/apply-template"], necessary if template else 0
                        )
                        self.assertEqual(
                            len(run.model.generations), merge_calls + (capacity == 1)
                        )
                        self.assertEqual(len(result[0]), 2 if capacity != 1 else 1)

    def test_small_inputs_keep_exact_evidence_fitting_and_engine_context(self):
        for count in (1, 2, 4):
            for template in (False, True):
                for compact in (False, True):
                    with self.subTest(count=count, template=template, compact=compact):
                        run, notes = self.new_run(count, template, evidence=True)
                        run.model.compact_final = compact
                        result = run._merge_until_final_fits(notes, "final")
                        self.assertEqual(result[0], notes)
                        self.assertEqual(
                            result[2],
                            0 if compact else reliability.EVIDENCE_PROMPT_CHARS,
                        )
                        self.assertEqual(len(run.model.fit_inputs), 2 if compact else 1)
                        self.assertEqual(
                            result[1],
                            reliability.combined(notes, run.evidence, result[2]),
                        )
                        self.assertEqual(run.model.generations, [])
        run, notes = self.new_run(1)
        run.model.capabilities["context_tokens"] = 64
        with self.assertRaises(ProcessingError) as caught:
            run._merge_until_final_fits(notes, "final")
        self.assertEqual(caught.exception.code, "merge_impossible")

    def test_merge_impossible_and_level_limit_still_apply(self):
        run, notes = self.new_run(5)
        run.model.merge_capacity = 1
        with self.assertRaises(ProcessingError) as caught:
            run._merge_until_final_fits(notes, "final")
        self.assertEqual(caught.exception.code, "merge_impossible")
        self.assertFalse(any(stage == "final" for stage, _ in run.model.fit_inputs))
        for count, capacity, success in ((120, 4, False), (2, 4, True), (2, 1, False)):
            with self.subTest(count=count, capacity=capacity):
                run, notes = self.new_run(count)
                run.model.final_capacity = capacity
                with patch.object(pipeline, "MAX_MERGE_LEVELS", 0):
                    if success:
                        self.assertEqual(
                            run._merge_until_final_fits(notes, "final")[0], notes
                        )
                    else:
                        with self.assertRaises(ProcessingError) as caught:
                            run._merge_until_final_fits(notes, "final")
                        self.assertEqual(caught.exception.code, "merge_impossible")
                self.assertEqual(run.model.generations, [])

    def test_cancel_and_shutdown_at_entry_and_between_mandatory_iterations(self):
        for template in (False, True):
            for error in (Cancelled, WorkerStopping):
                for after_merge in (False, True):
                    with self.subTest(
                        template=template, error=error, after_merge=after_merge
                    ):
                        run, notes = self.new_run(120, template)
                        signal = Mock(side_effect=error())
                        merge = run._merge_level

                        def merge_then_cancel(
                            *args, merge=merge, model=run.model, signal=signal
                        ):
                            result = merge(*args)
                            model.cancel_check = signal
                            return result

                        if after_merge:
                            run._merge_level = merge_then_cancel
                        else:
                            run.model.cancel_check = signal
                        with self.assertRaises(error):
                            run._merge_until_final_fits(notes, "final")
                        self.assertFalse(
                            any(stage == "final" for stage, _ in run.model.fit_inputs)
                        )
                        self.assertEqual(
                            len(run.model.generations), 30 if after_merge else 0
                        )

    def test_full_pipeline_matches_preoptimization_generations_reports_and_snapshots(
        self,
    ):
        golden = json.loads(GOLDEN.read_text())
        for count in (5, 8, 120):
            for template in (False, True):
                with self.subTest(count=count, template=template):
                    self.assertEqual(
                        pipeline_fixture(count, template), golden[str(count)]
                    )


